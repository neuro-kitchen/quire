#!/usr/bin/env bash
# Writes the book's reference pages from the binary itself, so they cannot drift:
#   docs/src/reference/cli.md     every command's --help
#   docs/src/reference/config.md  `quire config keys`
# Usage: docs/gen-reference.sh [path/to/quire]   (CI fails when the result differs from git)
set -euo pipefail

quire=${1:-target/debug/quire}
out=$(dirname "$0")/src/reference

# Help shows env values ([env: QUIRE_CONFIG=…]): run without the user's settings, fixed width.
q() { env -u QUIRE_CONFIG -u QUIRE_LIB -u QUIRE_LIBRARY NO_COLOR=1 COLUMNS=100 "$quire" "$@"; }

# Subcommand names listed under "Commands:" in a help text (without `help`).
subcommands() {
  awk '/^Commands:/ {on = 1; next} on && /^$/ {exit} on && $1 != "help" {print $1}'
}

walk() {
  local help
  help=$(q "$@" --help)
  printf '\n%s quire %s\n\n```text\n%s\n```\n' "$(printf '#%.0s' $(seq 1 $((${#} + 1))))" "$*" "$help"
  local sub
  for sub in $(subcommands <<<"$help"); do
    walk "$@" "$sub"
  done
}

{
  echo "# Command reference"
  echo
  echo "<!-- Generated by docs/gen-reference.sh from \`quire --help\`; do not edit. -->"
  echo
  echo "Every command's \`--help\`. The options \`--lib\`, \`--library\`, \`--config\` and \`-v\` work"
  echo "with every command."
  help=$(q --help)
  printf '\n## quire\n\n```text\n%s\n```\n' "$help"
  for sub in $(subcommands <<<"$help"); do
    [ "$sub" = completions ] || walk "$sub"
  done
} >"$out/cli.md"

{
  echo "# Settings reference"
  echo
  echo "<!-- Generated by docs/gen-reference.sh from \`quire config keys\`; do not edit. -->"
  echo
  echo "Settings live in \`~/.config/quire/config.toml\` (\`--config\` or \`QUIRE_CONFIG\` for another"
  echo "file). Change them with \`quire config set <key> <value>\`; \`*\` is a name you choose, e.g."
  echo "\`export.typst.format\`."
  echo
  echo "| Key | Meaning |"
  echo "|---|---|"
  q config keys | sed -E 's/^([^ ]+) +(.*)$/| `\1` | \2 |/'
} >"$out/config.md"
